"use client";

import Quiz from "@/components/Quiz/Quiz";
import CircleLoading from "@/ui/CircleLoading";
import { useState } from "react";
import { categories } from "@/data/categories";
import { isValidQuestion } from "@/lib/questionShape";
import { addLoss, addWin } from "@/actions/actions";
import { useSession } from "next-auth/react";
import StartButton from "@/ui/StartButton";
import Title from "@/ui/Title";

export default function QuizPage() {
  const [startGame, setStartGame] = useState(false);
  const [loadingGame, setLoadingGame] = useState(false);

  const [question, setQuestion] = useState("");
  const [answers, setAnswers] = useState<{ choice: string; answer: string }[]>(
    []
  );
  const [correctAnswer, setCorrectAnswer] = useState("");
  const [error, setError] = useState("");

  const [category, setCategory] = useState(categories[0]);

  // The server repairs invalid payloads itself (see lib/openai.ts), so this is
  // a thin outer guard rather than the primary retry path.
  const MAX_RETRIES = 1;

  const { data: session } = useSession();

  const handleNewGame = () => {
    setError("");
    setStartGame(true);
    fetchOneQuestion();
  };

  async function fetchOneQuestion(retryCount = 0) {
    setLoadingGame(true);
    setError("");
    try {
      const url = new URL("/api/getQuestions", window.location.origin);
      url.searchParams.set("prompt", category.prompt);
      url.searchParams.set("count", "1");

      const res = await fetch(url.toString());
      if (!res.ok) throw new Error(`HTTP error ${res.status}`);

      const payload = (await res.json()) as { data: unknown };
      const item = Array.isArray(payload.data) ? payload.data[0] : payload.data;

      if (!isValidQuestion(item)) {
        if (retryCount < MAX_RETRIES) {
          return fetchOneQuestion(retryCount + 1);
        }
        throw new Error("Invalid question structure after retries");
      }

      setQuestion(item.question);
      setAnswers(
        item.answers.map((answer, i) => ({
          choice: String.fromCharCode(65 + i),
          answer,
        }))
      );
      setCorrectAnswer(item.correctAnswer);
    } catch (err) {
      console.error("Error fetching question:", err);
      const message = err instanceof Error ? err.message : String(err);

      // Transport failures are not worth retrying; a bad payload is.
      if (!message.startsWith("HTTP") && retryCount < MAX_RETRIES) {
        return fetchOneQuestion(retryCount + 1);
      }

      // Surface it rather than rethrowing into an unhandled rejection.
      setError("Couldn't load a question. Please try again.");
    } finally {
      setLoadingGame(false);
    }
  }

  const handleAnswerSelected = async (selectedAnswer: string) => {
    if (selectedAnswer === correctAnswer) {
      await addWin(session?.user?.email ?? "", category.name);
    } else {
      await addLoss(session?.user?.email ?? "", category.name);
    }
  };

  return (
    <div className="flex flex-col flex-1 w-full max-w-[90rem] mx-auto">
      {!startGame ? (
        <div className="flex flex-col flex-1 md:justify-center items-center font-ibmPlexMono gap-y-6 md:gap-y-8 mt-8 md:mt-0">
          <div className="flex flex-col items-center justify-center gap-y-4">
            <Title title="How The Quiz Works" />
            <p className="max-w-[40rem] text-[var(--muted)] md:text-center text-start md:text-sm text-xs leading-relaxed">
              <span className="hidden md:block">
                Each game you get a unique web development question generated by
                OpenAI with 3 multiple choice answers. Select the correct answer to earn a
                win, or get a loss for incorrect answers. When you're
                ready, click Start Game. Good luck!
              </span>
              <span className="md:hidden block">
                Get unique AI-generated questions with three choices. Answer correctly to win,
                incorrectly to lose. Good luck!
              </span>
            </p>
          </div>
          <div className="flex flex-col justify-center items-center gap-y-4">
            <p className="text-xs md:text-sm font-medium text-[var(--muted)] uppercase tracking-wider">
              Choose Category
            </p>
            <div className="lg:w-[600px] md:w-[450px] mx-auto flex flex-wrap justify-center items-center gap-2">
              {categories.map((item, i) => (
                <button
                  onClick={() => {
                    setCategory(item);
                  }}
                  className={`lg:py-2 lg:px-4 md:py-1.5 md:px-3 py-1.5 px-2.5 lg:text-sm md:text-xs text-xs rounded-xl text-center w-fit transition-all duration-200 cursor-pointer ${
                    category === item
                      ? "bg-[var(--foreground)] text-[var(--background)] font-medium"
                      : "bg-[var(--card-bg)] border border-[var(--card-border)] hover:bg-[var(--card-bg-hover)]"
                  }`}
                  key={i}
                >
                  {item.name}
                </button>
              ))}
            </div>
          </div>
          <StartButton startGame={handleNewGame} title="START GAME" />
        </div>
      ) : loadingGame ? (
        <div className="flex w-full flex-1 items-center justify-center">
          <CircleLoading />
        </div>
      ) : error ? (
        <div className="flex w-full flex-1 flex-col items-center justify-center gap-y-4 font-ibmPlexMono">
          <p className="md:text-sm text-xs text-red-400 text-center">{error}</p>
          <div className="flex flex-row gap-3">
            <button
              className="bg-[var(--foreground)] hover:opacity-90 text-[var(--background)] md:py-2 md:px-4 py-1.5 px-3 rounded-lg md:text-sm text-xs font-medium transition-all duration-200"
              onClick={() => fetchOneQuestion()}
            >
              TRY AGAIN
            </button>
            <button
              className="bg-[var(--card-bg)] border border-[var(--card-border)] hover:bg-[var(--card-bg-hover)] md:py-2 md:px-4 py-1.5 px-3 rounded-lg md:text-sm text-xs font-medium transition-all duration-200"
              onClick={() => setStartGame(false)}
            >
              LEAVE
            </button>
          </div>
        </div>
      ) : (
        <Quiz
          setStartGame={setStartGame}
          newRound={fetchOneQuestion}
          question={question}
          answers={answers}
          correctAnswer={correctAnswer}
          onAnswerSelected={handleAnswerSelected}
        />
      )}
    </div>
  );
}
